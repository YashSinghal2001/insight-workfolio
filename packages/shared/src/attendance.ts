import { z } from "zod";

// ---- State machine ----------------------------------------------------------
// Single source of truth for the API (authoritative) and the desktop (offline preview).

export const ATTENDANCE_STATES = ["CLOCKED_OUT", "CLOCKED_IN", "ON_BREAK"] as const;
export type AttendanceState = (typeof ATTENDANCE_STATES)[number];

export const ATTENDANCE_EVENT_TYPES = ["CLOCK_IN", "BREAK_START", "BREAK_END", "CLOCK_OUT"] as const;
export type AttendanceEventType = (typeof ATTENDANCE_EVENT_TYPES)[number];

/** event -> [required state, resulting state]. Clock-out requires the break to be ended first. */
const TRANSITIONS: Record<AttendanceEventType, readonly [AttendanceState, AttendanceState]> = {
  CLOCK_IN: ["CLOCKED_OUT", "CLOCKED_IN"],
  BREAK_START: ["CLOCKED_IN", "ON_BREAK"],
  BREAK_END: ["ON_BREAK", "CLOCKED_IN"],
  CLOCK_OUT: ["CLOCKED_IN", "CLOCKED_OUT"],
};

/** Next state, or null when the transition is not allowed. */
export function transition(state: AttendanceState, event: AttendanceEventType): AttendanceState | null {
  const [from, to] = TRANSITIONS[event];
  return state === from ? to : null;
}

const ACTION = { CLOCK_IN: "clock in", BREAK_START: "start a break", BREAK_END: "end a break", CLOCK_OUT: "clock out" };
const STATE = { CLOCKED_OUT: "clocked out", CLOCKED_IN: "clocked in", ON_BREAK: "on a break" };

export function invalidTransitionMessage(state: AttendanceState, event: AttendanceEventType): string {
  return event === "CLOCK_OUT" && state === "ON_BREAK"
    ? "End your break before clocking out"
    : `Cannot ${ACTION[event]} while ${STATE[state]}`;
}

// ---- Calculations -----------------------------------------------------------
// Durations are differences of absolute UTC instants, so sessions crossing midnight or a
// daylight-saving change need no special handling; time zones only matter for display.

export interface Interval {
  start: string;
  /** null while still running; measured up to `now`. */
  end: string | null;
}

export interface AttendanceTotals {
  /** Clock-in to clock-out (or now). */
  elapsedMs: number;
  breakMs: number;
  /** elapsed - breaks: the working time. */
  netMs: number;
}

const span = ({ start, end }: Interval, now: number) => Math.max(0, (end ? Date.parse(end) : now) - Date.parse(start));

export function attendanceTotals(session: Interval, breaks: Interval[], now = Date.now()): AttendanceTotals {
  const elapsedMs = span(session, now);
  const breakMs = Math.min(elapsedMs, breaks.reduce((sum, b) => sum + span(b, now), 0));
  return { elapsedMs, breakMs, netMs: elapsedMs - breakMs };
}

/** Activity durations, where seconds matter: "2h 05m", "4m 07s", "38s". */
export function formatDurationShort(ms: number): string {
  const secs = Math.floor(Math.max(0, ms) / 1000);
  if (secs < 60) return `${secs}s`;
  if (secs < 3600) return `${Math.floor(secs / 60)}m ${String(secs % 60).padStart(2, "0")}s`;
  return formatDuration(ms);
}

/** "7h 05m"; seconds are dropped (floor). */
export function formatDuration(ms: number): string {
  const minutes = Math.floor(Math.max(0, ms) / 60_000);
  return `${Math.floor(minutes / 60)}h ${String(minutes % 60).padStart(2, "0")}m`;
}

// ---- API schemas ------------------------------------------------------------

export const DEVICE_PLATFORMS = ["macos", "windows"] as const;

export const registerDeviceSchema = z.object({
  /** Random per-installation UUID generated by the app. Never a hardware identifier. */
  installationId: z.uuid(),
  deviceName: z.string().trim().min(1).max(120),
  platform: z.enum(DEVICE_PLATFORMS),
});
export type RegisterDeviceInput = z.input<typeof registerDeviceSchema>;

/** Header sent by the desktop app on attendance requests. */
export const DEVICE_HEADER = "x-device-id";
export const IDEMPOTENCY_HEADER = "idempotency-key";
export const uuidSchema = z.uuid();

export const SYNC_BATCH_MAX = 100;

export const syncEventSchema = z.object({
  /** Client-generated; doubles as the idempotency key. */
  id: z.uuid(),
  type: z.enum(ATTENDANCE_EVENT_TYPES),
  /** Device clock when the employee pressed the button. */
  occurredAt: z.iso.datetime({ offset: true }),
});
export type SyncEvent = z.infer<typeof syncEventSchema>;

export const syncRequestSchema = z.object({
  /** Device clock when the request was sent; the server derives the clock skew from it. */
  sentAt: z.iso.datetime({ offset: true }),
  events: z.array(syncEventSchema).min(1).max(SYNC_BATCH_MAX),
});
export type SyncRequest = z.infer<typeof syncRequestSchema>;

export const pageQuerySchema = z.object({
  page: z.coerce.number().int().min(1).max(10_000).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(20),
});

/** History: optional local-date range (employee's time zone) and, for admins, an employee. */
export const historyQuerySchema = pageQuerySchema.extend({
  from: z.iso.date().optional(),
  to: z.iso.date().optional(),
  employeeId: z.uuid().optional(),
});
